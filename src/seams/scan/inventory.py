"""Which files the scan reads, which area each one belongs to, and the Lead record.

An area is a part of the repo that a separate session or team would edit on its
own: a package, a service, a top-level folder. Seams that cross areas matter
most, because nobody edits both sides in one change.
"""
from __future__ import annotations

import bisect
import os
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from .. import check

CODE_EXT = {
    ".py", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".vue", ".svelte", ".go", ".rs",
    ".java", ".kt", ".kts", ".scala", ".rb", ".php", ".cs", ".swift", ".c", ".h", ".cc",
    ".cpp", ".hpp", ".m", ".dart", ".ex", ".exs", ".lua", ".r", ".pl", ".sh", ".bash",
    ".zsh", ".sql", ".html", ".j2", ".jinja", ".tpl",
    # server-side templates: they re-state rules (a sign-up link behind a setting) and user-facing limits
    ".heex", ".eex", ".leex", ".erb", ".haml", ".slim", ".hbs", ".handlebars", ".mustache", ".njk",
    ".liquid", ".twig", ".ejs", ".pug", ".cshtml", ".razor", ".astro",
}
CONFIG_EXT = {".yml", ".yaml", ".toml", ".ini", ".cfg", ".conf", ".env", ".properties",
              ".tf", ".hcl", ".star", ".json", ".jsonc"}
CONFIG_NAMES = {"Dockerfile", "Makefile", "Procfile", "Caddyfile", "Justfile", ".env"}
DOC_EXT = {".md", ".mdx", ".rst"}  # docs that state code facts: CLAUDE.md, ARCHITECTURE.md, catalogs

SKIP_PARTS = {".git", "node_modules", "vendor", "third_party", "third-party", "dist", "build",
              "__pycache__", ".venv", "venv", "site-packages", "coverage", ".next", ".nuxt",
              "target", ".tox", ".mypy_cache", ".pytest_cache", ".ruff_cache", ".seams-scan"}
SKIP_NAMES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock",
              "Cargo.lock", "go.sum", "composer.lock", "Gemfile.lock", "Pipfile.lock"}
SKIP_SUFFIXES = (".min.js", ".min.css", ".map", ".snap", ".lock")
MAX_BYTES = 1_000_000

MANIFESTS = {"package.json", "pyproject.toml", "setup.py", "setup.cfg", "go.mod", "Cargo.toml",
             "pom.xml", "build.gradle", "build.gradle.kts", "Gemfile", "composer.json",
             "mix.exs", "pubspec.yaml", "deno.json", "Dockerfile"}
CONTAINERS = {"src", "lib", "libs", "app", "apps", "packages", "services", "modules", "cmd",
              "internal", "pkg", "components", "projects", "crates", "plugins"}

TEST_PARTS = {"test", "tests", "__tests__", "spec", "specs", "testing", "e2e"}
_TEST_NAME = re.compile(r"^(test_.*|.*_test\.\w+|.*\.(test|spec)\.\w+|conftest\.py|.*Tests?\.(java|kt|cs)|.*_spec\.rb)$")
_GENERATED = re.compile(r"@generated|DO NOT EDIT|auto-?generated|generated by", re.I)
# The seams tool's own files: the registry, its baseline and notes, and the checker that
# `seams init` copies in (found by its header, wherever --checker put it). Scanning them
# only finds the tool itself.
OWN_FILES = {"seams.json", "seams.baseline.json"}
# Note files come from the checker's own table, so a new notes mode is skipped here too.
OWN_PARTS = ("/.seams-scan/",) + tuple(f"/{folder}/{prefix}" for folder, prefix, _ in check.NOTE_FILES.values())
_CHECKER_HEAD = '"""Check a repo\'s seams registry (seams.json) against the repo.'


def is_own(path, head=""):
    return (path in OWN_FILES or any(part in "/" + path for part in OWN_PARTS)
            or (path.endswith(".py") and _CHECKER_HEAD in head[:300]))


def is_minified(head):
    """Most lines very long. One long line is not enough: tsc writes a 1,500-character
    `exports.a = exports.b = ... = void 0;` line at the top of a readable file."""
    lines = head.split("\n")[:50]
    long = sum(len(line) > 1000 for line in lines)
    return long >= 3 or sum(map(len, lines)) / max(1, len(lines)) > 300


def is_test(path):
    parts = path.split("/")
    return bool(TEST_PARTS & set(parts[:-1])) or bool(_TEST_NAME.match(parts[-1]))


def kind_of(path):
    """'code', 'config', 'doc' or None for a file the scan does not read."""
    name = path.rsplit("/", 1)[-1]
    if name in CONFIG_NAMES or name.startswith(".env"):
        return "config"
    ext = os.path.splitext(name)[1].lower()
    if ext in CODE_EXT:
        return "code"
    if ext in CONFIG_EXT:
        return "config"
    if ext in DOC_EXT:
        return "doc"
    return None


@dataclass
class Lead:
    """One hint that a seam may exist. Leads are cheap and many are noise."""
    kind: str
    locs: list  # [(path, line, end_line or None)]
    detail: str
    score: float = 1.0
    extra: dict = field(default_factory=dict)


def _git_files(root):
    try:
        run = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if run.returncode != 0:
        return None
    return [p for p in run.stdout.decode("utf-8", "replace").split("\0") if p]


def _walk_files(root):
    out = []
    for here, dirs, names in os.walk(root, followlinks=False):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_PARTS)
        rel = Path(here).relative_to(root).as_posix()
        out += [n if rel == "." else f"{rel}/{n}" for n in sorted(names)]
    return out


class Inventory:
    def __init__(self, root):
        self.root = Path(root)
        listed = _git_files(self.root)
        self.source = "git" if listed is not None else "walk"
        listed = listed if listed is not None else _walk_files(self.root)

        self.files = []        # every listed file that still exists
        self.read = []         # files the scan reads: code and config, not skipped
        self.generated = []    # files that say they are generated: single sources at work
        self.skipped = {}      # files of a type the scan reads, left unread: path -> reason
        self.own = []          # the seams tool's own files
        self._text = {}
        self._newlines = {}
        for p in sorted(set(listed)):
            full = self.root / p
            if not full.is_file() or full.is_symlink():
                continue
            self.files.append(p)
            parts = p.split("/")
            if SKIP_PARTS & set(parts[:-1]) or parts[-1] in SKIP_NAMES or p.endswith(SKIP_SUFFIXES):
                continue
            if kind_of(p) is None:
                continue
            try:
                if full.stat().st_size > MAX_BYTES:
                    self.skipped[p] = f"over {MAX_BYTES // 1_000_000} MB"
                    continue
                raw = full.read_bytes()
            except OSError:
                self.skipped[p] = "unreadable"
                continue
            if b"\0" in raw[:8192]:
                self.skipped[p] = "binary"
                continue
            text = raw.decode("utf-8", "replace")
            head = text[:4000]
            if is_minified(head):
                self.skipped[p] = "minified"
                continue
            if is_own(p, head):
                self.own.append(p)
                continue
            if _GENERATED.search("\n".join(head.split("\n")[:5])):
                self.generated.append(p)
                continue
            self._text[p] = text
            self.read.append(p)

        self._roots = {os.path.dirname(p) for p in self.files
                       if p.rsplit("/", 1)[-1] in MANIFESTS or p.endswith(".csproj")} - {""}
        self._area = {p: self._area_of(p) for p in self.files}
        self._by_name = {}
        for p in self.files:
            self._by_name.setdefault(p.rsplit("/", 1)[-1], []).append(p)

    def _area_of(self, path):
        d = os.path.dirname(path)
        while d:
            if d in self._roots:
                return d
            d = os.path.dirname(d)
        parts = path.split("/")
        if len(parts) == 1:
            return "(root)"
        if parts[0] in CONTAINERS and len(parts) > 2:
            return "/".join(parts[:2])
        return parts[0]

    def area(self, path):
        return self._area.get(path) or self._area_of(path)

    def text(self, path):
        return self._text.get(path, "")

    def line_at(self, path, offset):
        """1-based line number of a character offset in a file's text."""
        starts = self._newlines.get(path)
        if starts is None:
            text = self.text(path)
            starts = self._newlines[path] = [m.start() for m in re.finditer("\n", text)]
        return bisect.bisect_left(starts, offset) + 1

    def code(self, tests=True):
        return [p for p in self.read if kind_of(p) == "code" and (tests or not is_test(p))]

    def areas(self):
        """[(area, files read, lines)] largest first."""
        stats = {}
        for p in self.read:
            a = stats.setdefault(self.area(p), [0, 0])
            a[0] += 1
            a[1] += self._text[p].count("\n") + 1
        return sorted(((a, n, l) for a, (n, l) in stats.items()), key=lambda r: -r[2])

    def lines(self):
        return sum(t.count("\n") + 1 for t in self._text.values())

    def resolve_mention(self, token, exclude=None):
        """Files a path-like token in text probably names, or []."""
        token = token.strip("'\"`()[]<>,.:;")
        while token.startswith(("./", "../")):
            token = token.split("/", 1)[1]
        if not token or "/" not in token and "." not in token:
            return []
        if token in self._area:
            return [] if token == exclude else [token]
        hits = self._by_name.get(token.rsplit("/", 1)[-1], [])
        if "/" in token:
            hits = [p for p in hits if p.endswith("/" + token)]
        hits = [h for h in hits if h != exclude]
        return hits if len(hits) <= 3 else []
